#!/usr/bin/env bash
# Builds the JAR and deploys Lambda functions + API Gateway REST APIs with the AWS CLI.
# Idempotent: run it again to update code and API definitions.
#
# Usage:  ./deploy/deploy.sh            (uses the default AWS profile / region)
#         AWS_PROFILE=lab AWS_REGION=us-east-1 ./deploy/deploy.sh
#         LAMBDA_ROLE_ARN=arn:aws:iam::<account>:role/LabRole ./deploy/deploy.sh
set -euo pipefail
export MSYS_NO_PATHCONV=1   # Git Bash on Windows: do not rewrite "/orders"-like arguments into file paths
export AWS_PAGER=""

cd "$(dirname "$0")/.."
source deploy/config.sh

echo "== Building $JAR"
env -u MSYS_NO_PATHCONV mvn -q -DskipTests package   # mvn launcher breaks with MSYS_NO_PATHCONV

# ---------------------------------------------------------------- IAM execution role
# Set LAMBDA_ROLE_ARN to reuse an existing role (e.g. AWS Academy "LabRole", where iam:CreateRole is denied).
if [[ -n "${LAMBDA_ROLE_ARN:-}" ]]; then
  ROLE_ARN="$LAMBDA_ROLE_ARN"
  echo "== Using existing role $ROLE_ARN"
elif ! ROLE_ARN=$(aws iam get-role --role-name "$ROLE_NAME" --query Role.Arn --output text 2>/dev/null); then
  echo "== Creating role $ROLE_NAME"
  ROLE_ARN=$(aws iam create-role --role-name "$ROLE_NAME" \
    --assume-role-policy-document file://deploy/lambda-trust-policy.json --query Role.Arn --output text)
  aws iam attach-role-policy --role-name "$ROLE_NAME" \
    --policy-arn arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole
  echo "   waiting for IAM propagation..."; sleep 12
fi

# ---------------------------------------------------------------- Lambda functions
deploy_function() {  # name handler
  local name="$1" handler="$2"
  if aws lambda get-function --function-name "$name" >/dev/null 2>&1; then
    echo "== Updating function $name"
    aws lambda update-function-code --function-name "$name" --zip-file "fileb://$JAR" >/dev/null
    aws lambda wait function-updated --function-name "$name"
    aws lambda update-function-configuration --function-name "$name" --handler "$handler" >/dev/null
    aws lambda wait function-updated --function-name "$name"
  else
    echo "== Creating function $name"
    aws lambda create-function --function-name "$name" --runtime java17 --role "$ROLE_ARN" \
      --handler "$handler" --zip-file "fileb://$JAR" --memory-size 512 --timeout 15 >/dev/null
    aws lambda wait function-active --function-name "$name"
  fi
}

for entry in "${FUNCTIONS[@]}"; do
  deploy_function "${entry%%=*}" "${entry#*=}"
done

# ---------------------------------------------------------------- API Gateway
render() {  # openapi template -> rendered file
  sed -e "s/\${REGION}/$AWS_REGION/g" -e "s/\${ACCOUNT_ID}/$ACCOUNT_ID/g" -e "s/\${FN_PREFIX}/$FN_PREFIX/g" "$1" > "$2"
}

deploy_api() {  # api-name template-file functions...
  local api_name="$1" template="$2"; shift 2
  local rendered="target/${api_name}.rendered.yaml"
  render "$template" "$rendered"

  local api_id
  api_id=$(aws apigateway get-rest-apis --query "items[?name=='$api_name'].id | [0]" --output text)
  if [[ "$api_id" == "None" || -z "$api_id" ]]; then
    echo "== Importing REST API $api_name" >&2
    api_id=$(aws apigateway import-rest-api --parameters endpointConfigurationTypes=REGIONAL \
      --body "fileb://$rendered" --query id --output text)
  else
    echo "== Overwriting REST API $api_name ($api_id)" >&2
    aws apigateway put-rest-api --rest-api-id "$api_id" --mode overwrite \
      --body "fileb://$rendered" >/dev/null
  fi

  for fn in "$@"; do
    aws lambda add-permission --function-name "$fn" --statement-id "apigw-$api_id" \
      --action lambda:InvokeFunction --principal apigateway.amazonaws.com \
      --source-arn "arn:aws:execute-api:$AWS_REGION:$ACCOUNT_ID:$api_id/*/*/*" >/dev/null 2>&1 || true
  done

  aws apigateway create-deployment --rest-api-id "$api_id" --stage-name "$STAGE" >/dev/null
  local url="https://$api_id.execute-api.$AWS_REGION.amazonaws.com/$STAGE"
  echo "   $api_name -> $url" >&2
  printf '%s\n' "$url"
}

MAPPING_URL=$(deploy_api orders-api-mapping apigateway/orders-api-mapping.yaml "${MAPPING_FUNCTIONS[@]}")
PROXY_URL=$(deploy_api orders-api-proxy apigateway/orders-api-proxy.yaml "${PROXY_FUNCTIONS[@]}")

cat > deploy/outputs.env <<EOF
# Generated by deploy/deploy.sh
MAPPING_URL=$MAPPING_URL
PROXY_URL=$PROXY_URL
EOF
echo
cat deploy/outputs.env
